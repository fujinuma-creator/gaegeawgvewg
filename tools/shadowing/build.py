#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate ShadowingSeed.swift from sentences.py, with British-RP IPA for
each sentence from espeak-ng (-v en-gb-x-rp --ipa).

    python3 tools/shadowing/build.py
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "EnglishVocabApp", "EnglishVocabApp", "ShadowingSeed.swift")
sys.path.insert(0, HERE)
from sentences import SENTENCES  # noqa: E402


def ipa(sentence):
    out = subprocess.run(["espeak-ng", "-q", "-v", "en-gb-x-rp", "--ipa", sentence],
                         capture_output=True, text=True, timeout=20).stdout
    return " ".join(out.split()).replace("_", " ").strip()


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    seen = set()
    rows = []
    for sid, en, ja, tips in SENTENCES:
        assert sid not in seen, sid
        seen.add(sid)
        tip_list = ",\n                   ".join(q(t) for t in tips)
        rows.append(
            f"        ShadowingItem(id: {q(sid)},\n"
            f"                      english: {q(en)},\n"
            f"                      japanese: {q(ja)},\n"
            f"                      ipa: {q(ipa(en))},\n"
            f"                      tips: [{tip_list}]),"
        )
    swift = (
        "import Foundation\n\n"
        "/// 発音 → シャドウイングの文。\n"
        "/// Generated by tools/shadowing/build.py from tools/shadowing/sentences.py — edit there.\n"
        "/// Audio: put ShadowingAudio/shadow_<id>.m4a (and optionally shadow_<id>.json,\n"
        "/// a JSON array with each word's start time in seconds) in the app; without a\n"
        "/// file the sentence is read by the iPhone voice.\n"
        "enum ShadowingSeed {\n"
        "    static let all: [ShadowingItem] = [\n"
        + "\n".join(rows) + "\n"
        "    ]\n"
        "}\n"
    )
    open(OUT, "w", encoding="utf-8").write(swift)
    print(f"sentences {len(SENTENCES)} -> {OUT}")


if __name__ == "__main__":
    main()
