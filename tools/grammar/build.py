#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate GrammarSeed.swift from topics.py, adding British-RP IPA for every
example sentence with espeak-ng (-v en-gb-x-rp --ipa).

    python3 tools/grammar/build.py
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "EnglishVocabApp", "EnglishVocabApp", "GrammarSeed.swift")
sys.path.insert(0, HERE)
from topics import TOPICS  # noqa: E402

LEVELS = {"beginner": ".beginner", "basic": ".basic", "intermediate": ".intermediate", "advanced": ".advanced"}


def ipa(sentence):
    try:
        out = subprocess.run(["espeak-ng", "-q", "-v", "en-gb-x-rp", "--ipa", sentence],
                             capture_output=True, text=True, timeout=20).stdout
    except Exception:
        return ""
    out = " ".join(out.split())
    return out.replace("_", " ").strip()


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = ["import Foundation", "",
             "/// 文法画面のデータ。入門 → 上級の順に、番号つきで並ぶ。",
             "/// Generated by tools/grammar/build.py from tools/grammar/topics.py — edit there.",
             "enum GrammarSeed {", "",
             "    static func topics(for level: TopicLevel) -> [GrammarTopic] {",
             "        all.filter { $0.level == level }",
             "    }", "",
             "    private static func c(_ t: String, _ l: String, _ tint: Int) -> GrammarChunk { GrammarChunk(text: t, label: l, tint: tint) }",
             "    private static func e(_ en: String, _ ipa: String, _ ja: String) -> GrammarExample { GrammarExample(english: en, ipa: ipa, japanese: ja) }",
             "",
             "    static let all: [GrammarTopic] = ["]
    seen = set()
    for t in TOPICS:
        assert t["id"] not in seen, t["id"]
        seen.add(t["id"])
        lines.append("")
        lines.append("        GrammarTopic(")
        lines.append(f'            id: {q(t["id"])}, level: {LEVELS[t["level"]]}, title: {q(t["title"])},')
        lines.append(f'            summary: {q(t["summary"])}, sample: {q(t["sample"])},')
        lines.append(f'            detailTitle: {q(t["detailTitle"])}, detailSubtitle: {q(t["detailSubtitle"])},')
        lines.append("            sections: [")
        for sec in t["sections"]:
            chunks = ", ".join(f"c({q(a)}, {q(b)}, {tint})" for a, b, tint in sec["chunks"])
            lines.append(f'                GrammarSection(heading: {q(sec["heading"])}, keyword: {q(sec["keyword"])},')
            lines.append(f"                               chunks: [{chunks}],")
            exs = []
            for en, ja in sec["examples"]:
                exs.append(f"e({q(en)}, {q(ipa(en))}, {q(ja)})")
            lines.append("                               examples: [" + ",\n                                          ".join(exs) + "]),")
        lines.append("            ],")
        lines.append(f'            tipTitle: {q(t["tipTitle"])},')
        lines.append(f'            tip: {q(t["tip"])},')
        lines.append(f'            wrong: {q(t["wrong"])}, right: {q(t["right"])}),')
    lines.append("    ]")
    lines.append("}")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    n = sum(len(s["examples"]) for t in TOPICS for s in t["sections"])
    print(f"topics {len(TOPICS)}  examples {n}  -> {OUT}")


if __name__ == "__main__":
    main()
